"""Render evals/results/*.json into the results section of EVALS.md.

    python evals/report.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "evals" / "results"
EVALS_MD = ROOT / "EVALS.md"
START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"

METRICS = ["route_correct", "retrieval_hit", "numeric_accuracy", "faithfulness", "citation_precision",
           "key_point_recall", "goal_proposed"]
OPS = ["latency_p50_s", "latency_p95_s", "cost_per_query_usd", "rewrite_rate", "errors"]
ORDER = ["final", "final_repeat", "baseline", "baseline_repeat", "ab_mini", "ab_no_rerank", "ab_single_query", "claim_check",
         "prompt_v1", "no_citation_loop", "temp_0", "temp_07", "top_p_05"]


def fmt(v):
    if v is None:
        return "—"
    if isinstance(v, dict):
        return f"{v['mean']:.2f} (n={v['n']})"
    return f"{v}"


def table(reports: list[dict]) -> str:
    head = "| metric | " + " | ".join(r["config"] for r in reports) + " |"
    sep = "|---|" + "---|" * len(reports)
    lines = [head, sep]
    for m in METRICS + OPS:
        lines.append(f"| {m} | " + " | ".join(fmt(r["aggregate"].get(m)) for r in reports) + " |")
    return "\n".join(lines)


def by_category(rep: dict) -> str:
    cats: dict[str, list[int]] = {}
    for r in rep["results"]:
        cats.setdefault(r["category"], []).append(r["scores"]["route_correct"]["score"])
    rows = ["| category | n | route accuracy |", "|---|---|---|"]
    for c, v in cats.items():
        rows.append(f"| {c} | {len(v)} | {sum(v) / len(v):.2f} |")
    return "\n".join(rows)


def failures(rep: dict, limit: int = 12) -> str:
    out = []
    for r in rep["results"]:
        bad = [f"{k}={v['score']:.2f}" for k, v in r["scores"].items() if v["score"] is not None and v["score"] < 0.75]
        if bad:
            out.append(f"- **{r['id']}** ({r['category']}) “{r['question']}” → {', '.join(bad)}")
    return "\n".join(out[:limit]) or "_none_"


def main():
    reports = {p.stem: json.loads(p.read_text()) for p in RESULTS.glob("*.json")}
    if not reports:
        print("no results yet — run evals/run.py first")
        return
    ordered = [reports[k] for k in ORDER if k in reports] + [v for k, v in reports.items() if k not in ORDER]
    md = [f"_Generated by `evals/report.py` from `evals/results/` · judge model: {ordered[0].get('judge_model')}_\n",
          "### All configurations\n", table(ordered)]
    if "baseline" in reports:
        md += ["\n### Baseline — route accuracy by category\n", by_category(reports["baseline"]),
               "\n### Baseline — examples scoring < 0.75 on any metric\n", failures(reports["baseline"])]
    block = "\n".join(md)
    text = EVALS_MD.read_text(encoding="utf-8")
    if START in text:
        pre, rest = text.split(START, 1)
        post = rest.split(END, 1)[1] if END in rest else ""
        text = f"{pre}{START}\n{block}\n{END}{post}"
    else:
        text += f"\n{START}\n{block}\n{END}\n"
    EVALS_MD.write_text(text, encoding="utf-8")
    print(block)


if __name__ == "__main__":
    main()
